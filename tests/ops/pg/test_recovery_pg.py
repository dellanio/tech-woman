def participant(email):
    return "(select id from participant where email='%s')" % email


class RecoveryWorld(unittest.TestCase):
    """A migrated synthetic techwoman database on PostgreSQL 16 and a host in pg_write_open with a real baseline."""

    def setUp(self):
        self.cluster = Cluster()
        self.version = self.cluster.ensure()
        self.db = self.cluster.create_database('techwoman_t')
        self.addCleanup(self.drop_databases)
        for role in ('techwoman_runtime', 'techwoman_mailer'):
            self.cluster.psql('postgres', "do $$ begin if not exists (select 1 from pg_roles where rolname='%s') "
                                          "then create role %s nologin; end if; end $$" % (role, role))
        migrated = subprocess.run(['node', '--import', 'tsx', 'scripts/migration/migrate.ts'], cwd=ROOT,
                                  env=dict(os.environ, MIGRATION_DATABASE_URL=self.cluster.url(self.db)),
                                  capture_output=True, text=True)
        self.assertEqual(migrated.returncode, 0, migrated.stderr)
        self.q(FIXTURE)
        self.host = Host(self, pg_db=self.db, env=self.cluster.env())
        (self.host.ops.fake / 'pg-passthrough').write_bytes(b'')
        self.sqlite_path, writer = self.host.sqlite()
        writer.close()
        candidate, state = self.host.imported()
        state.transition('activated', NOW_FIXED, activation={'digest': OLD_PG_DIGEST, 'container': 'tech-woman-web-pg',
                                                             'at': NOW_FIXED})
        state.transition('smoke_ok', NOW_FIXED)
        self.baseline = json.loads(self.q(BASELINE))
        state.transition('pg_write_open', NOW_FIXED, known_pg_images=[OLD_PG_DIGEST], last_good_pg_image=OLD_PG_DIGEST,
                         schema_migrations={'aggregate_sha256': candidate['migrations']['aggregate_sha256']},
                         first_pg_write={'at': None, 'kind': None, 'baseline': self.baseline})
        (self.host.ops.fake / 'container-inspect').write_bytes(('%s|%s\n' % (OLD_PG_IMAGE, ORIGINAL_IP)).encode())
        self.sqlite_bytes = self.sqlite_path.read_bytes()

    def drop_databases(self):
        names = self.cluster.psql('postgres', "select datname from pg_database where datname like '%s%%'" % self.db)
        for name in names.split():
            self.cluster.drop_database(name)

    def q(self, sql, db=None):
        return self.cluster.psql(db or self.db, sql)

    def state(self):
        return cutover.State.load(self.host.state_dir, cutover.UNCHECKED)

    def reserve(self, email):
        """A reservation through the product triggers (match, email_job, audit_event come from the schema)."""
        return int(self.q("insert into enrollment(participant_id,cohort_id,status) select %s, id, 'active' from cohort "
                          "returning id" % participant(email)).split()[0])

    def assert_never_sqlite(self):
        log = self.host.cutover_log_text()
        self.assertNotIn('tech-woman-sqlite-original', log)
        self.assertNotIn('sqlite', log.lower())
        self.assertEqual(self.sqlite_path.read_bytes(), self.sqlite_bytes)

    def assert_no_pii(self, done):
        self.assertNotIn('example.invalid', done.stdout + done.stderr)


class FirstWriteTests(RecoveryWorld):
    def test_no_write_since_the_baseline_records_nothing(self):
        done = self.host.cutover('record-first-write')
        self.assertEqual(done.returncode, 0, done.stderr)
        self.assertEqual(json.loads(done.stdout), {'first_pg_write': None})
        self.assertEqual(self.state().data['first_pg_write']['kind'], None)

    def test_the_first_reservation_after_the_baseline_is_recorded_by_kind_and_time_only(self):
        self.reserve('p1@example.invalid')
        done = self.host.cutover('record-first-write')
        self.assertEqual(done.returncode, 0, done.stderr)
        first = json.loads(done.stdout)['first_pg_write']
        self.assertEqual(first['kind'], 'enrollment.create')
        self.assertRegex(first['at'], r'^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ$')
        recorded = self.state().data['first_pg_write']
        self.assertEqual((recorded['kind'], recorded['at'], recorded['baseline']), (first['kind'], first['at'], self.baseline))
        self.assertEqual(self.state().phase, 'pg_write_open')
        self.assert_no_pii(done)
        self.assertEqual(self.host.cutover('record-first-write').returncode, 75)  # recorded once, never rewritten
        self.assert_never_sqlite()


class RestartRecoveryTests(RecoveryWorld):
    """R-A: the app and PostgreSQL fail; committed data survives a crash restart and the PG web comes back."""

    def test_committed_reservation_survives_an_immediate_restart_and_recovery_reopens_on_postgres(self):
        enrollment = self.reserve('p1@example.invalid')
        self.assertEqual(self.host.cutover('record-first-write').returncode, 0)
        # an application transaction in flight when everything dies: it must vanish, not half-persist
        in_flight = subprocess.Popen(['psql', '-X', '-q', '-v', 'ON_ERROR_STOP=1', '-d', self.db, '-c',
                                      "begin; insert into enrollment(participant_id,cohort_id,status) select %s, id, "
                                      "'active' from cohort; select pg_sleep(60); commit;" % participant('p2@example.invalid')],
                                     env=self.cluster.env(), stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        self.addCleanup(in_flight.kill)
        deadline = time.time() + 30
        while time.time() < deadline and 'PgSleep' not in self.q("select string_agg(coalesce(wait_event,''),',') "
                                                                 "from pg_stat_activity where datname=current_database()"):
            time.sleep(0.1)
        self.q("select pg_terminate_backend(pid) from pg_stat_activity where datname=current_database() "
               "and pid <> pg_backend_pid()")
        self.cluster.restart_immediate()

        done = self.host.cutover('recover', '--mode', 'restart')
        self.assertEqual(done.returncode, 0, done.stderr)
        report = json.loads(done.stdout)
        self.assertEqual(report['mode'], 'restart')
        self.assertEqual(report['phase'], 'pg_write_open')
        live = report['live']
        self.assertEqual(live['tables']['enrollment'], self.baseline['enrollment'] + 1)
        self.assertEqual(live['tables']['match'], self.baseline['match'] + 1)
        self.assertTrue(live['first_write_present'])
        self.assertEqual(live['sequences_behind'], 0)
        self.assert_no_pii(done)

        # independent readback: the committed reservation and everything the product derived from it
        self.assertEqual(self.q("select status from enrollment where id=%d" % enrollment).strip(), 'active')
        self.assertEqual(self.q("select count(*) from enrollment where participant_id=%s" % participant('p2@example.invalid')).strip(), '0')
        self.assertEqual(self.q("select count(*) from match where enrollment_id=%d and status='selected'" % enrollment).strip(), '1')
        self.assertEqual(self.q("select count(*) from email_job where enrollment_id=%d and kind='reservation'" % enrollment).strip(), '1')
        self.assertEqual(self.q("select count(*) from audit_event where entity_id='%d' and action='enrollment.create'" % enrollment).strip(), '1')
        after = self.reserve('p2@example.invalid')
        self.assertGreater(after, enrollment)  # the sequence did not go back after the crash

        calls = [c['args'] for c in self.host.cutover_calls() if c['cmd'] == 'docker']
        self.assertIn(['start', 'tech-woman'], calls)
        self.assertIn(['start', 'tech-woman-mailer'], calls)
        self.assertEqual(calls.index(['start', 'tech-woman']) < calls.index(['start', 'tech-woman-mailer']), True)
        state = self.state()
        self.assertEqual(state.phase, 'pg_write_open')
        self.assertEqual(state.data['recovery']['mode'], 'restart')
        journal = [json.loads(line)['phase'] for line in (self.host.state_dir / 'journal.jsonl').read_text().splitlines()]
        self.assertEqual(journal[-2:], ['recovering', 'pg_write_open'])
        self.assert_never_sqlite()

    def test_a_web_that_is_not_a_known_postgres_image_is_never_restarted(self):
        (self.host.ops.fake / 'container-inspect').write_bytes(('%s|%s\n' % ('ghcr.io/dellanio/tech-woman@sha256:' + '0' * 64,
                                                                             ORIGINAL_IP)).encode())
        done = self.host.cutover('recover', '--mode', 'restart')
        self.assertEqual(done.returncode, 76, done.stderr)
        docker = [c['args'] for c in self.host.cutover_calls() if c['cmd'] == 'docker']
        self.assertEqual([a for a in docker if a[0] in ('start', 'run', 'rename', 'rm', 'stop')], [])
        self.assertEqual(self.state().phase, 'recovering')  # deploys stay denied until the operator decides
        self.assert_never_sqlite()


class RestoreRecoveryTests(RecoveryWorld):
    """R-B: an older dump restored in isolation proves what it lacks; recovery is a RECENT complete dump of the
    intact database, restored in isolation and confronted row by row with the source (no partial delta)."""

    def daily_dump(self):
        """What the host's daily mechanism produced before the reservation (pg_dump -Fc of the whole database)."""
        path = self.host.ops.host / 'backups' / 'daily-20261023.dump'
        with open(path, 'wb') as out:
            done = subprocess.run(['pg_dump', '-Fc', '-d', self.db], stdout=out, stderr=subprocess.PIPE, env=self.cluster.env())
        self.assertEqual(done.returncode, 0, done.stderr)
        return path.name

    def writes_after_the_dump(self):
        first = self.reserve('p1@example.invalid')
        self.assertEqual(self.host.cutover('record-first-write').returncode, 0)
        dump = self.daily_dump()
        second = self.reserve('p2@example.invalid')                     # new reservation after the dump
        self.q("update enrollment set status='cancelled' where id=%d" % first)  # and a cancellation (UPDATE)
        return dump, first, second

    def table_digests(self, db):
        rows = self.q("select n.nspname||'.'||c.relname from pg_class c join pg_namespace n on n.oid=c.relnamespace "
                      "where c.relkind='r' and n.nspname not in ('pg_catalog','information_schema') "
                      "and n.nspname not like 'pg\\_%' order by 1", db).split()
        return {t: self.q("select count(*)||':'||coalesce(md5(string_agg(x::text, '|' order by x::text)),'') from %s x"
                          % '.'.join('"%s"' % p for p in t.split('.')), db).strip() for t in rows}

    def test_an_older_dump_lacks_the_reservation_and_the_cancellation_and_says_so(self):
        dump, first, second = self.writes_after_the_dump()
        done = self.host.cutover('recover', '--mode', 'compare', '--dump', dump)
        self.assertEqual(done.returncode, 86, done.stderr)
        report = json.loads(done.stdout)
        self.assertFalse(report['equal'])
        differences = report['differences']
        self.assertEqual(differences['public.enrollment'], {'only_live': 1, 'only_restored': 0, 'changed': 1})
        self.assertEqual(differences['public.match'], {'only_live': 1, 'only_restored': 0, 'changed': 1})
        self.assertEqual(differences['public.email_job'], {'only_live': 1, 'only_restored': 0, 'changed': 1})
        self.assertEqual(differences['public.audit_event'], {'only_live': 2, 'only_restored': 0, 'changed': 0})
        restored = report['restored_db']
        self.assertTrue(restored.startswith(self.db + '_restore_'))
        # explicit: the isolated restore of the older dump does NOT contain the reservation made after it
        self.assertEqual(self.q("select count(*) from enrollment where id=%d" % second, restored).strip(), '0')
        self.assertEqual(self.q("select status from enrollment where id=%d" % first, restored).strip(), 'active')
        self.assertEqual(self.state().phase, 'pg_write_open')  # inspection only
        self.assert_no_pii(done)
        self.assert_never_sqlite()

    def test_recovery_is_a_recent_complete_dump_proven_identical_to_the_intact_source(self):
        dump, first, second = self.writes_after_the_dump()
        live = self.table_digests(self.db)
        done = self.host.cutover('recover', '--mode', 'reconcile')
        self.assertEqual(done.returncode, 0, done.stderr)
        report = json.loads(done.stdout)
        self.assertTrue(report['equal'])
        self.assertEqual(report['differences'], {})
        self.assertTrue(report['schema_equal'])
        self.assertEqual(report['phase'], 'pg_write_open')
        restored = report['restored_db']
        # independent check: every row of every table, ids/status/timestamps included, sequences too
        self.assertEqual(self.table_digests(restored), live)
        seq = "select string_agg(sequencename||'='||coalesce(last_value::text,''), ',' order by 1) from pg_sequences"
        self.assertEqual(self.q(seq, restored), self.q(seq))
        self.assertEqual(self.q("select status, cancelled_at is not null from enrollment where id=%d" % first, restored).strip(), 'cancelled|t')
        self.assertEqual(self.q("select count(*) from match where enrollment_id=%d" % second, restored).strip(), '1')
        recovery_dump = self.host.ops.host / 'backups' / report['dump']
        self.assertNotEqual(report['dump'], dump)
        if os.name == 'posix':
            self.assertEqual(os.stat(recovery_dump).st_mode & 0o777, 0o600)
        recovery = self.state().data['recovery']
        self.assertEqual((recovery['mode'], recovery['result'], recovery['restored_db']), ('reconcile', 'ok', restored))
        import hashlib
        self.assertEqual(recovery['dump_sha256'], hashlib.sha256(recovery_dump.read_bytes()).hexdigest())
        self.assert_no_pii(done)
        self.assert_never_sqlite()

    def test_an_update_that_creates_no_new_id_is_still_a_difference(self):
        dump = self.daily_dump()
        self.q("update mentor set availability='noites' where email='m1@example.invalid'")  # no row above any id
        done = self.host.cutover('recover', '--mode', 'compare', '--dump', dump)
        self.assertEqual(done.returncode, 86, done.stderr)
        self.assertEqual(json.loads(done.stdout)['differences'],
                         {'public.mentor': {'only_live': 0, 'only_restored': 0, 'changed': 1}})

    def test_without_a_readable_live_database_nothing_is_restored_and_the_rpo_is_stated(self):
        self.reserve('p1@example.invalid')
        # the PostgreSQL container is gone: every `docker exec` into it fails
        (self.host.ops.fake / 'pg-passthrough').unlink()
        (self.host.ops.fake / 'exec.rc').write_bytes(b'1')
        for mode in (['--mode', 'reconcile'], ['--mode', 'restart']):
            with self.subTest(mode=mode[1]):
                done = self.host.cutover('recover', *mode)
                self.assertEqual(done.returncode, 85, done.stderr)
                self.assertIn('ate 24h (dump diario)', done.stderr)
                self.assertIn('decision', done.stderr)
                self.assertIn('no success is claimed', done.stderr)
                self.assertEqual(done.stdout, '')
                self.assertEqual(self.state().phase, 'recovering')
        self.assertEqual(self.q("select count(*) from pg_database where datname like '%s%%restore%%'" % self.db).strip(), '0')
        self.assertEqual([c for c in self.host.cutover_calls() if c['cmd'] == 'docker' and c['args'][0] in ('start', 'run')], [])
        self.assert_never_sqlite()


